// Equipamiento y deudas en cuotas, de punta a punta (20/11). Los montos son
// inventados.
const { chromium } = require('playwright')
const A = require('./ayudas.cjs')
const CAP = A.CAPTURAS
const hoy = A.dia(0), mes = hoy.slice(0, 7)
const gasto = (id, dia, concepto, monto, categoria = 'OTROS') => ({ id, fecha: `${mes}-${dia}`, tipo: 'GASTO_CAJA_GRANDE', cuenta: 'banco', concepto, monto, categoria, jornadaId: null, esVariable: true })

;(async () => {
  const uid = await A.crearUsuario('emma@prueba.test')
  await A.poner(`usuarios/${uid}`, { id: uid, email: 'emma@prueba.test', nombre: 'Emmanuel', rol: 'owner', activo: true })
  await A.poner('usuarios/sin-cuenta-elena', { id: 'sin-cuenta-elena', email: '', nombre: 'Elena', rol: 'owner', activo: true, sinCuenta: true })
  await A.sembrar('movimientos', [gasto('o1', '12', 'cuota compu', 100001), gasto('o2', '13', 'Heladera', 200002)])
  const b = await chromium.launch()
  const ctx = await b.newContext({ timezoneId: 'America/Argentina/Cordoba', locale: 'es-AR', viewport: { width: 1280, height: 900 } })
  const p = await A.entrar(ctx, 'emma@prueba.test')
  const preguntas = []
  p.on('dialog', async (d) => { preguntas.push(d.message()); await d.accept() })

  console.log('\n===== Vencimientos: la deuda de la compu, en cuotas, con Elena =====')
  await p.goto(A.URL + '#/vencimientos'); await p.waitForTimeout(2500)
  await p.locator('button', { hasText: '+ Agregar un vencimiento' }).click()
  await p.locator('button', { hasText: 'Una deuda en cuotas' }).click()
  console.log('categoría que propone:', await p.locator('#v-categoria').inputValue(), '| ¿marcó «en cuotas»?', await p.locator('input[type="checkbox"]').isChecked())
  await p.locator('#v-concepto').fill('Compu del local')
  await p.locator('#v-dia').fill('10')
  await p.locator('#v-monto').fill('100001')
  await p.locator('#v-cuotas').fill('6')
  await p.locator('#v-primera').fill('2')
  await p.locator('#v-periodo-cuota').fill(mes)
  console.log('a quién se le puede deber:', (await p.locator('#v-a-quien option').allInnerTexts()).join(' / '))
  await p.locator('#v-a-quien').selectOption({ label: 'Elena' })
  await p.screenshot({ path: `${CAP}/deuda-formulario.png`, fullPage: true })
  await p.locator('button', { hasText: 'Agregar a la agenda' }).click(); await p.waitForTimeout(1500)
  const renglon = p.locator('li.item', { hasText: 'Compu del local' }).last()
  console.log('RENGLÓN:', await A.texto(renglon))
  console.log('DEUDAS:', await A.texto(p.locator('section[aria-label="Deudas en cuotas"]')))
  const v = (await A.listar('vencimientos'))[0]
  console.log('SERVIDOR vencimiento:', JSON.stringify({ categoria: v.categoria, cuotas: v.cuotas, aQuien: v.aQuien, desde: v.desde, esVariable: v.esVariable }))

  await renglon.locator('button', { hasText: 'Marcar pagado' }).click(); await p.waitForTimeout(500)
  console.log('AL PAGAR:', (await A.texto(renglon.locator('.aviso-ojo'))).slice(0, 160), '| etiqueta:', await renglon.locator('label[for^="pv-monto-"]').innerText())
  console.log('ORDEN de los candidatos:', (await renglon.locator('.aviso-ojo .item-titulo').allInnerTexts()).join(' / '))
  await renglon.locator('li.item', { hasText: 'cuota compu' }).locator('button', { hasText: 'Es este' }).click(); await p.waitForTimeout(1500)
  console.log('AVISO:', await A.texto(p.locator('.aviso-ok').first()))
  console.log('DEUDAS después:', await A.texto(p.locator('section[aria-label="Deudas en cuotas"]')))
  const o1 = await A.leer('movimientos/o1')
  console.log('SERVIDOR la cuota que estaba como OTROS:', JSON.stringify({ categoria: o1.categoria, esVariable: o1.esVariable, persona: o1.persona, vencimiento: o1.vencimiento }))
  await p.screenshot({ path: `${CAP}/deuda-agenda.png`, fullPage: true })

  console.log('\n===== Gastos: «a Elena» y el selector de categoría =====')
  await p.goto(A.URL + '#/gastos'); await p.waitForTimeout(2500)
  console.log('CUOTA en la lista:', await A.texto(p.locator('li.item', { hasText: 'cuota compu' }).locator('.item-sub').first()))
  await p.locator('select[aria-label="Categoría de Heladera"]').selectOption('EQUIPAMIENTO'); await p.waitForTimeout(1500)
  const o2 = await A.leer('movimientos/o2')
  console.log('SERVIDOR la heladera:', o2.categoria, o2.esVariable ? 'variable' : 'fijo', '| persona:', o2.persona ?? '(ninguna)', '| vencimiento:', o2.vencimiento ? 'sí' : 'no')
  console.log('HELADERA en la lista:', await A.texto(p.locator('li.item', { hasText: 'Heladera' }).locator('.item-sub').first()))
  const hist = (await A.listar('historial')).filter((h) => h.tabla === 'movimientos')
  console.log('HISTORIAL:', [...new Set(hist.map((h) => `${h.campo}: ${h.motivo}`))].sort().join(' ; '))
  await p.screenshot({ path: `${CAP}/gastos-categoria.png`, fullPage: true })
  console.log('PREGUNTAS que hizo:', preguntas.length)
  console.log('\nRECHAZOS anotados en el servidor:', (await A.listar('rechazos')).length)
  await b.close()
})().catch((e) => { console.error('FALLO:', e); process.exit(1) })
